#!/usr/bin/env python3
"""Track feature points through prepared plates (per-point NCC template matching).

Usage: track_points.py <plates_dir> <tracking_config.json> <out tracks.js>

Config format:
  {"shots": {"<name>": {"range": [first, last], "ref": refFrame,
                         "points": [[x, y], ...]}}}
Coordinates are in plate pixels (1080x1920). Points are tracked forwards and
backwards from the reference frame. A point that leaves the frame becomes null.
The result is written as a JS file (window.TRACKS = {...}) so the composition
can load it from file:// without fetch().
"""
import json
import sys

import numpy as np
from numpy.lib.stride_tricks import sliding_window_view
from PIL import Image

SCALE = 2          # track on half-resolution plates
RADIUS = 18        # template half-size (half-res px)
SEARCH = 10        # search half-range per frame (half-res px)

plates_dir, config_path, out_path = sys.argv[1:4]
config = json.load(open(config_path))
_cache = {}


def plate(i):
    if i not in _cache:
        im = Image.open(f"{plates_dir}/f{i:04d}.jpg").convert("L")
        im = im.resize((1080 // SCALE, 1920 // SCALE), Image.BILINEAR)
        _cache[i] = np.asarray(im, np.float32)
    return _cache[i]


def subpixel(c, m, p):
    d = m - 2 * c + p
    return 0.0 if d == 0 else 0.5 * (m - p) / d


def step(prev, cur, pt):
    if pt is None:
        return None
    x, y = pt
    xi, yi = int(round(x)), int(round(y))
    tpl = prev[yi - RADIUS:yi + RADIUS + 1, xi - RADIUS:xi + RADIUS + 1]
    win = cur[yi - RADIUS - SEARCH:yi + RADIUS + SEARCH + 1,
              xi - RADIUS - SEARCH:xi + RADIUS + SEARCH + 1]
    if yi - RADIUS - SEARCH < 0 or xi - RADIUS - SEARCH < 0 or \
            tpl.shape != (2 * RADIUS + 1,) * 2 or win.shape != (2 * (RADIUS + SEARCH) + 1,) * 2:
        return None
    views = sliding_window_view(win, tpl.shape)
    t0 = tpl - tpl.mean()
    v0 = views - views.mean(axis=(2, 3), keepdims=True)
    ncc = (v0 * t0).sum(axis=(2, 3)) / (np.sqrt((v0 * v0).sum(axis=(2, 3)) * (t0 * t0).sum()) + 1e-6)
    py, px = np.unravel_index(np.argmax(ncc), ncc.shape)
    oy = subpixel(ncc[py, px], ncc[py - 1, px], ncc[py + 1, px]) if 0 < py < ncc.shape[0] - 1 else 0.0
    ox = subpixel(ncc[py, px], ncc[py, px - 1], ncc[py, px + 1]) if 0 < px < ncc.shape[1] - 1 else 0.0
    return (x + (px - SEARCH) + ox, y + (py - SEARCH) + oy)


tracks = {}
for name, shot in config["shots"].items():
    first, last = shot["range"]
    ref = shot["ref"]
    start = [(x / SCALE, y / SCALE) for x, y in shot["points"]]
    frames = {ref: start}
    for rng in (range(ref + 1, last + 1), range(ref - 1, first - 1, -1)):
        pts, prev = start, plate(ref)
        for i in rng:
            cur = plate(i)
            pts = [step(prev, cur, p) for p in pts]
            frames[i] = pts
            prev = cur
    tracks[name] = {
        "first": first,
        "last": last,
        "frames": {str(i): [None if p is None else [round(p[0] * SCALE, 1), round(p[1] * SCALE, 1)] for p in pts]
                   for i, pts in sorted(frames.items())},
    }
    print(f"{name}: {len(frames)} frames, {len(start)} points")

with open(out_path, "w") as f:
    f.write("// generated by scripts/track_points.py - do not edit\n")
    f.write("window.TRACKS = " + json.dumps(tracks, separators=(",", ":")) + ";\n")
